"""
Write docs/data.js from the Python package, so the browser app and the Python code share
one set of defaults, presets and UI controls.

    python tools/build_data.py

Run it after changing BoardParams, presets.py or schema.py. tests/test_js_parity.py fails
if docs/data.js is out of date.
"""
import json
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from surfboard import BoardParams, PRESETS, NOSE_TYPES, TAIL_TYPES   # noqa: E402
from surfboard.schema import GROUPS, STATION_TABLE                   # noqa: E402

OUT = ROOT / "docs" / "data.js"


def render() -> str:
    parts = ["// Generated by tools/build_data.py from the Python package. Do not edit by hand.\n"]
    for name, value in (("DEFAULTS", asdict(BoardParams())), ("NOSE_TYPES", NOSE_TYPES),
                        ("TAIL_TYPES", TAIL_TYPES), ("PRESETS", PRESETS),
                        ("GROUPS", GROUPS), ("STATION_TABLE", STATION_TABLE)):
        parts.append(f"export const {name} = {json.dumps(value, indent=2)};\n")
    return "\n".join(parts)


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
